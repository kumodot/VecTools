/* Local corner offsets, indexed by corner id (see the diagram above). */
const CORNER_DX = new Int32Array([0, 1, 1, 0, 0, 1, 1, 0]);
const CORNER_DY = new Int32Array([0, 0, 1, 1, 0, 0, 1, 1]);
const CORNER_DZ = new Int32Array([0, 0, 0, 0, 1, 1, 1, 1]);

/*
 * Edge endpoints, ORDERED so that the corner with the smaller global linear
 * index (x + nx*(y + ny*z)) always comes first. Within a cell that ordering is
 * 0 < 1 < 3 < 2 < 4 < 5 < 7 < 6, so edges 2, 3, 6 and 7 are stored reversed
 * relative to the classic 2-3 / 3-0 / 6-7 / 7-4 listing.
 *
 * This matters: the same physical edge is visited by up to four neighbouring
 * cells, and interpolating it from the same ordered pair of corners every time
 * makes the resulting vertex position bit-for-bit identical. Welding is then
 * exact and the mesh comes out watertight.
 */
const EDGE_A = new Int32Array([0, 1, 3, 0, 4, 5, 7, 4, 0, 1, 2, 3]);
const EDGE_B = new Int32Array([1, 2, 2, 3, 5, 6, 6, 7, 4, 5, 6, 7]);

/**
 * Growable Float32 buffer made of fixed-size chunks, so that very large
 * outputs never go through a plain JS array of numbers.
 */
class FloatChunks {
  /** @param {number} chunkFloats Floats per chunk (multiple of 9). */
  constructor(chunkFloats) {
    this.chunkFloats = chunkFloats;
    this.chunks = [new Float32Array(chunkFloats)];
    this.current = this.chunks[0];
    this.used = 0;
    this.total = 0;
  }

  /** Reserve room for one more triangle (9 floats). @returns {void} */
  ensureTriangle() {
    if (this.used + 9 > this.chunkFloats) {
      this.current = new Float32Array(this.chunkFloats);
      this.chunks.push(this.current);
      this.used = 0;
    }
  }

  /**
   * Append one float. Call ensureTriangle() before each group of 9.
   * @param {number} v
   * @returns {void}
   */
  push(v) {
    this.current[this.used++] = v;
    this.total++;
  }

  /** @returns {Float32Array} A single compacted array of every pushed float. */
  flatten() {
    const out = new Float32Array(this.total);
    let off = 0;
    for (let c = 0; c < this.chunks.length; c++) {
      const chunk = this.chunks[c];
      const len = c === this.chunks.length - 1 ? this.used : this.chunkFloats;
      out.set(chunk.subarray(0, len), off);
      off += len;
    }
    return out;
  }
}

/**
 * Polygonise a scalar field with Marching Cubes.
 *
 * INSIDE CONVENTION: a sample is inside the surface when `field[i] < iso`.
 * This matches a signed distance field that is negative inside. The classic
 * Bourke tables use the same convention (the corner bit is set when the value
 * is below the isolevel), but they were written for data where high values are
 * inside, so the emitted winding is clockwise when viewed from the low-value
 * side. Every triangle is therefore emitted with its second and third vertices
 * SWAPPED relative to the raw table, which makes the front face point away
 * from the negative (inside) region - i.e. outward-facing normals under a
 * right-handed, counter-clockwise front-face convention.
 *
 * @param {Float32Array} field  Scalar samples, length nx*ny*nz, indexed as
 *   x + nx*(y + ny*z).
 * @param {number} nx  Samples along x.
 * @param {number} ny  Samples along y.
 * @param {number} nz  Samples along z.
 * @param {number} [iso=0]  Iso level.
 * @param {(t: number) => void} [onProgress]  Optional callback receiving a
 *   0..1 completion fraction roughly every 2% of the z slices.
 * @returns {{positions: Float32Array, triangleCount: number}} Non-indexed
 *   triangle soup in GRID INDEX SPACE, 9 floats per triangle.
 */
export function marchingCubes(field, nx, ny, nz, iso = 0, onProgress) {
  const nxy = nx * ny;
  const out = new FloatChunks(9 * 8192);

  // Per-cell scratch, reused for every cell.
  const cv = new Float64Array(8);   // corner values
  const cx = new Float64Array(8);   // corner x
  const cy = new Float64Array(8);   // corner y
  const cz = new Float64Array(8);   // corner z
  const ex = new Float64Array(12);  // edge vertex x
  const ey = new Float64Array(12);
  const ez = new Float64Array(12);

  const cellsZ = nz - 1;
  const progressEvery = Math.max(1, Math.floor(cellsZ / 50));
  let triangleCount = 0;

  for (let z = 0; z < cellsZ; z++) {
    for (let y = 0; y < ny - 1; y++) {
      const base = nx * (y + ny * z);
      for (let x = 0; x < nx - 1; x++) {
        const i0 = base + x;

        // Gather the 8 corner values.
        const v0 = field[i0];
        const v1 = field[i0 + 1];
        const v2 = field[i0 + 1 + nx];
        const v3 = field[i0 + nx];
        const v4 = field[i0 + nxy];
        const v5 = field[i0 + 1 + nxy];
        const v6 = field[i0 + 1 + nx + nxy];
        const v7 = field[i0 + nx + nxy];

        let cubeIndex = 0;
        if (v0 < iso) cubeIndex |= 1;
        if (v1 < iso) cubeIndex |= 2;
        if (v2 < iso) cubeIndex |= 4;
        if (v3 < iso) cubeIndex |= 8;
        if (v4 < iso) cubeIndex |= 16;
        if (v5 < iso) cubeIndex |= 32;
        if (v6 < iso) cubeIndex |= 64;
        if (v7 < iso) cubeIndex |= 128;

        const edgeMask = EDGE_TABLE[cubeIndex];
        if (edgeMask === 0) continue;

        cv[0] = v0; cv[1] = v1; cv[2] = v2; cv[3] = v3;
        cv[4] = v4; cv[5] = v5; cv[6] = v6; cv[7] = v7;
        for (let c = 0; c < 8; c++) {
          cx[c] = x + CORNER_DX[c];
          cy[c] = y + CORNER_DY[c];
          cz[c] = z + CORNER_DZ[c];
        }

        for (let e = 0; e < 12; e++) {
          if ((edgeMask & (1 << e)) === 0) continue;
          const a = EDGE_A[e];
          const b = EDGE_B[e];
          const va = cv[a];
          const vb = cv[b];
          const den = vb - va;
          const mu = den === 0 ? 0.5 : (iso - va) / den;
          ex[e] = cx[a] + mu * (cx[b] - cx[a]);
          ey[e] = cy[a] + mu * (cy[b] - cy[a]);
          ez[e] = cz[a] + mu * (cz[b] - cz[a]);
        }

        const rowBase = cubeIndex * 16;
        for (let t = 0; t < 16; t += 3) {
          const e0 = TRI_TABLE[rowBase + t];
          if (e0 < 0) break;
          // Winding flipped (e0, e2, e1) - see the note in the JSDoc above.
          const e1 = TRI_TABLE[rowBase + t + 2];
          const e2 = TRI_TABLE[rowBase + t + 1];

          out.ensureTriangle();
          out.push(ex[e0]); out.push(ey[e0]); out.push(ez[e0]);
          out.push(ex[e1]); out.push(ey[e1]); out.push(ez[e1]);
          out.push(ex[e2]); out.push(ey[e2]); out.push(ez[e2]);
          triangleCount++;
        }
      }
    }

    if (onProgress && (z % progressEvery === 0)) {
      onProgress(cellsZ > 0 ? z / cellsZ : 1);
    }
  }

  if (onProgress) onProgress(1);

  return { positions: out.flatten(), triangleCount };
}
